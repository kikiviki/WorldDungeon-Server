--   * One entry point: every combo's start_zone is kerraridge (74), so the
--     client's city-selection step collapses to a single option.
--   * RoF2-only. Titanium validates against a hardcoded C++ matrix
--     (CheckCharCreateInfoTitanium, world/client.cpp:2002) and ignores this
--     table entirely; it will only ever offer canonical combos.
--
-- ⚠️ OWNERSHIP DEVIATION, DELIBERATE: this DELETEs the 641 stock rows, which
-- F1's rule normally forbids. Content flags are not an option here - the
-- table has no content_flags column, and the stock rows are not "content" but
-- creation POLICY, which WorldDungeon owns outright. The stock rows are fully
-- recoverable from any PEQ source dump if ever needed.
--
-- allocation_id (the racial starting-stat spread, char_create_point_allocations):
-- combos that exist in stock keep their stock allocation; combos that never
-- existed use their race's lowest stock allocation id as a stand-in. A12
-- (flatten racial stats) will revisit every one of these.
--
-- ⚠️ WORLD RESTART REQUIRED: world caches this table for the char-create
-- packet. Zones are not involved.
--
-- Idempotent: full DELETE + INSERT; the table is wholly owned from now on.

